public class Nested {
    
    public static void main(String[] args) {
        int a, b, c;
        for(a = 1; a <= 2; a++) {
            for(b = 1; b <= 3; b++) {
                for(c = 1; c <= 2; c++) {
                    System.out.println("Hello");
                }
            }
        }
    }
}
